from __future__ import annotations
import argparse
import glob
import json
import time
from pathlib import Path
import numpy as np
import lib_fullcal as fl
import run_limits_m as rm
from run_bonfrank import run_bonfrank
from run_scalar_baselines import run_soft_baselines
from run_final_panel import run_static_perbook
from arbcal import config as CFG
from arbcal import repricing as rp
from arbcal.polyhedron import polyhedron_rows
from arbcal.scenarios import shrunk_cov
REPO = Path(__file__).resolve().parents[1]
MS = REPO / '.'
NS = fl.NAMESPACE
ALPHA = 0.1
HEADER = '% AUTO-GENERATED by scripts/make_ablation_table.py -- do not hand-edit.\n'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--panel', required=True)
    ap.add_argument('--losses-glob', required=True)
    ap.add_argument('--nu', type=float, default=3.0)
    args = ap.parse_args()
    t0 = time.time()
    vsrun = fl.load_vs_run()
    days, S, F, DISC, C = fl.load_panel(args.panel)
    masks = fl.panel_masks(days, fl.load_manifest())
    vt = masks['vt']
    D = len(days)
    L = fl.realized_losses(days, S, F, DISC, C, vt)
    mu, sd = vsrun.rolling_loc_scale(L)
    gamma = float(json.load(open(NS / 'fullcal_canonical.json'))['meta']['gamma_selected'][f'{ALPHA:g}'])
    SLp = rm.load_losses(args.losses_glob, days, vt)
    M = next(iter(SLp.values())).shape[0]
    n_bad = {}
    seed_base = None
    for f in sorted(glob.glob(args.losses_glob)):
        c = np.load(f, allow_pickle=True)
        sb = int(c['seed_base'])
        assert seed_base in (None, sb)
        seed_base = sb
        for row, t in enumerate(np.asarray(c['t_idx'], int)):
            n_bad[int(t)] = int(c['n_proj_bad'][row]) + int(c['n_proj_fail'][row])
    print(f'[abl2x2] {len(SLp)} scen dates, M={M} ({time.time() - t0:.0f}s)')
    arms_def = []
    r = fl.run_rank_method(ALPHA, D, L, mu, sd, SLp, M, gamma=gamma)
    arms_def.append(r['defined'])
    e_rank_proj = r['exceed']
    arms_def.append(fl.run_rank_method(ALPHA, D, L, mu, sd, SLp, M, gamma=0.0)['defined'])
    scen_i = {t: i for i, t in enumerate(sorted(SLp))}
    SL_list = [SLp[t] for t in sorted(SLp)]
    ba, _ = run_bonfrank(ALPHA, gamma, D, L, mu, sd, SL_list, scen_i)
    arms_def += [ba['bonfrank']['defined'], ba['bonfrank_fixed']['defined']]
    nom = run_static_perbook(ALPHA, D, L, mu, sd, SLp, M, lambda a: 1.0 - a)
    arms_def.append(nom['defined'])
    e_nom_proj = nom['exceed']
    arms_def.append(run_soft_baselines(ALPHA, D, L, mu, sd)['fhs_bonf']['defined'])
    za = np.load(NS / 'fullcal_arrays.npz', allow_pickle=True)
    arms_def.append(np.asarray(za[f'a{ALPHA:g}_direct_defined'], bool))
    common = np.ones(D, bool)
    for d_ in arms_def:
        common &= d_
    pm = common & masks['primary']
    print(f'[abl2x2] common primary dates: {pm.sum()} ({time.time() - t0:.0f}s)')
    assert int(pm.sum()) == 1161, int(pm.sum())
    G, h, fam = polyhedron_rows()
    SLr = {}
    viol_raw = {}
    for i, t in enumerate(sorted(SLp)):
        innov, Yv_full = fl.gap_innovations(S, C, vt, t)
        E = innov[-CFG.LW_WINDOW:]
        K = shrunk_cov(E)
        mu_d = np.concatenate([[0.0], Yv_full[-1]])
        rng = np.random.default_rng(seed_base + t)
        Lc = np.linalg.cholesky(K)
        eps = rng.standard_normal((M, len(mu_d))) @ Lc.T
        W = rng.chisquare(args.nu, size=M)
        eps = eps * np.sqrt((args.nu - 2.0) / W)[:, None]
        draws = mu_d[None, :] + eps
        R = draws[:, 0]
        Zraw = draws[:, 1:]
        viol_raw[t] = float(np.mean((Zraw @ G.T - h[None, :] > CFG.FEAS_TOL).any(axis=1)))
        surf_raw = Zraw.reshape(M, CFG.N_X, CFG.N_TAU)
        books = rp.build_books(S[t - 1], F[t - 1], DISC[t - 1], C[t - 1])
        St = S[t - 1] * np.exp(R)
        Fm, Dm = rp.scenario_forward_discount(St, S[t - 1], F[t - 1], DISC[t - 1])
        sl = np.empty((M, fl.K_BOOKS))
        for j, name in enumerate(fl.BOOKS):
            sl[:, j] = rp.book_loss_bps(books[name], St, Fm, Dm, surf_raw)
        SLr[t] = sl
        if (i + 1) % 100 == 0:
            print(f'[abl2x2] raw {i + 1}/{len(SLp)} ({time.time() - t0:.0f}s)', flush=True)
    e_nom_raw = run_static_perbook(ALPHA, D, L, mu, sd, SLr, M, lambda a: 1.0 - a)['exceed']
    e_rank_raw = fl.run_rank_method(ALPHA, D, L, mu, sd, SLr, M, gamma=gamma)['exceed']

    def fwe(e):
        return float(np.nanmean(e[pm]))
    vr_raw = float(np.mean([viol_raw[t] for t in sorted(SLp) if pm[t]]))
    vr_proj = float(np.mean([n_bad[t] / M for t in sorted(SLp) if pm[t]]))
    res = {'meta': {'law': 't', 'nu': args.nu, 'M': M, 'alpha': ALPHA, 'n_common_primary': int(pm.sum()), 'gamma': gamma, 'violation_rate': 'fraction of scenario surfaces outside A at FEAS_TOL; projected rate from chunk metadata (residual violations + projection failures)'}, 'rows': {'raw_nominal': {'fwe': fwe(e_nom_raw), 'viol': vr_raw}, 'proj_nominal': {'fwe': fwe(e_nom_proj), 'viol': vr_proj}, 'raw_rank_aci': {'fwe': fwe(e_rank_raw), 'viol': vr_raw}, 'proj_rank_aci': {'fwe': fwe(e_rank_proj), 'viol': vr_proj}}}
    outj = MS / 'results/q2q3_final_panel/ablation_2x2_t3.json'
    outj.write_text(json.dumps(res, indent=1, default=float))

    def vcell(v):
        return '0' if v == 0.0 else f'{v:.3f}'
    rows = res['rows']
    body = HEADER + '\n'.join(['\\begin{tabular}{@{}llcc@{}}', '\\toprule', 'surfaces & limit rule & FWE & violations \\\\', '\\midrule', f"unprojected & nominal & {rows['raw_nominal']['fwe']:.3f} & {vcell(rows['raw_nominal']['viol'])} \\\\", f"projected   & nominal & {rows['proj_nominal']['fwe']:.3f} & {vcell(rows['proj_nominal']['viol'])} \\\\", f"unprojected & max-rank ACI & {rows['raw_rank_aci']['fwe']:.3f} & {vcell(rows['raw_rank_aci']['viol'])} \\\\", f"projected   & max-rank ACI & {rows['proj_rank_aci']['fwe']:.3f} & {vcell(rows['proj_rank_aci']['viol'])} \\\\", '\\bottomrule', '\\end{tabular}']) + '\n'
    (MS / 'results/tab_ablation_main_t3_2018_2022.tex').write_text(body)
    print(json.dumps(res['rows'], indent=1))
    print(f'[abl2x2] wrote results/tab_ablation_main_t3_2018_2022.tex ({time.time() - t0:.0f}s)')
if __name__ == '__main__':
    main()
