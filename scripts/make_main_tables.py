from __future__ import annotations
import json
from pathlib import Path
REPO = Path(__file__).resolve().parents[1]
MS = REPO / '.'
NS = REPO / 'results'
FP = MS / 'results/q2q3_final_panel'
OUT = MS / 'results'
HEADER = '% AUTO-GENERATED by scripts/make_main_tables.py -- do not hand-edit.\n'

def fwe_cell(s):
    return f"{s['fwe']:.3f} [{s['fwe_lo']:.3f}, {s['fwe_hi']:.3f}]"

def dres_cell(s):
    dv = s['dres_vs_nominal']
    return f"{dv['mean']:+.2f} [{dv['lo']:+.2f}, {dv['hi']:+.2f}]"

def main():
    canon = json.load(open(NS / 'fullcal_canonical.json'))
    arb = json.load(open(NS / 'arb_margin_fullcal.json'))
    t3 = json.load(open(FP / 'final_panel_t3.json'))
    gauss = json.load(open(FP / 'final_panel_gauss.json'))
    ea = canon['experiment_a']['rw']['primary']
    m = arb['periods']['2018_2022']
    assert m['n_dates'] == ea['n_scored'] == 1223

    def margin_cell(b):
        return f"{b['median']:.1f} [{b['median_ci95'][0]:.1f}, {b['median_ci95'][1]:.1f}]"
    rows1 = [('raw joint ball', ea['coverage_raw_ball'], m['raw_ball']['violator_date_rate'], margin_cell(m['raw_ball'])), ('joint box', ea['coverage_joint_box'], m['joint_box']['violator_date_rate'], margin_cell(m['joint_box'])), ('\\ACSet{}', ea['coverage_projected_set'], 0.0, '0')]
    body1 = HEADER + '\n'.join(['\\begin{tabular}{@{}lccc@{}}', '\\toprule', 'method', '  & coverage', '  & \\shortstack{violator-date\\\\rate}', '  & \\shortstack{worst margin\\\\median [95\\% CI]} \\\\', '\\midrule', *[f'{name}\n  & {cov:.3f}\n  & {vr:.3f}\n  & {mg} \\\\' for name, cov, vr, mg in rows1], '\\bottomrule', '\\end{tabular}']) + '\n'
    (OUT / 'tab_surface_main_2018_2022.tex').write_text(body1)
    METHODS = (('nominal', 'nominal $t_3$ quantiles'), ('bonfrank_static', 'per-book Bonferroni'), ('rank_roll', 'rolling max-rank'), ('rank_aci', '\\ACRank{}'))
    lines = ['\\begin{tabular}{@{}clccc@{}}', '\\toprule', 'target', '  & method', '  & FWE [95\\% CI]', '  & \\shortstack{finite\\\\availability}', '  & \\shortstack{reserve $\\Delta$ vs nominal\\\\{}[95\\% CI]} \\\\', '\\midrule']
    for i, alpha in enumerate((0.1, 0.05, 0.01)):
        blk = t3['alphas'][f'{alpha:g}']
        lines.append('')
        lines.append(f'\\multirow{{4}}{{*}}{{${100 * (1 - alpha):g}\\%$}}')
        for key, disp in METHODS:
            s = blk[key]['primary']
            d = 'ref.' if key == 'nominal' else dres_cell(s)
            lines.append(f"  & {disp}\n  & {fwe_cell(s)}\n  & {s['finite_avail']:.3f}\n  & {d} \\\\")
        if alpha != 0.01:
            lines.append('\\addlinespace')
    lines += ['', '\\bottomrule', '\\end{tabular}']
    (OUT / 'tab_limits_main_t3_2018_2022.tex').write_text(HEADER + '\n'.join(lines) + '\n')
    ea23 = canon['experiment_a']['rw']['y2023']
    m23 = arb['periods']['2023']
    aux = [HEADER.rstrip(), '% 2023 locked temporal validation — numerical references for prose (t3 headline, common 246 dates).', '% -- scenario-derived limits (final_panel_t3.json, y2023) --']
    for key, disp in METHODS:
        for alpha in (0.1, 0.05, 0.01):
            s = t3['alphas'][f'{alpha:g}'][key]['y2023']
            aux.append(f"% {disp:26s} {100 * (1 - alpha):2.0f}%: FWE {fwe_cell(s)}, avail {s['finite_avail']:.3f}, reserve {s['mean_reserve_finite']:.2f}")
    aux += [f"% -- surface sets (alpha=0.10; canonical ExpA y2023 + arb_margin 2023, n={m23['n_dates']}) --", f"% coverage: ball {ea23['coverage_raw_ball']:.3f}, box {ea23['coverage_joint_box']:.3f}, set {ea23['coverage_projected_set']:.3f}", '% margins: ball ' + f"{m23['raw_ball']['median']:.1f} [{m23['raw_ball']['median_ci95'][0]:.1f}, {m23['raw_ball']['median_ci95'][1]:.1f}]" + ', box ' + f"{m23['joint_box']['median']:.1f} [{m23['joint_box']['median_ci95'][0]:.1f}, {m23['joint_box']['median_ci95'][1]:.1f}]" + ', set 0 (by construction)']
    (OUT / 'tab_validation_2023_rows.tex').write_text('\n'.join(aux) + '\n')
    aux = [HEADER.rstrip(), '% Working-law robustness: ArbCal-Rank ACI under Gaussian vs selected t3 (primary 2018-2022, common 1,161 dates).']
    for tag, d in (('gauss', gauss), ('t3', t3)):
        for alpha in (0.1, 0.05, 0.01):
            s = d['alphas'][f'{alpha:g}']['rank_aci']['primary']
            aux.append(f"% {tag:5s} {100 * (1 - alpha):2.0f}%: FWE {fwe_cell(s)}, avail {s['finite_avail']:.3f}, finite reserve {s['mean_reserve_finite']:.2f}")
    (OUT / 'tab_gaussian_robustness_rows.tex').write_text('\n'.join(aux) + '\n')
    aux = [HEADER.rstrip(), '% Scalar limit methods vs ArbCal-Rank ACI (t3 headline; paired reserve delta over common finite dates).']
    for key, disp in (('direct', 'direct max-score ACI'), ('fhs', 'filtered historical simulation')):
        for per in ('primary', 'y2023'):
            for alpha in (0.1, 0.05, 0.01):
                s = t3['alphas'][f'{alpha:g}'][key][per]
                dv = s['dres_vs_rank_aci']
                aux.append(f"% {disp:30s} {per:7s} {100 * (1 - alpha):2.0f}%: FWE {fwe_cell(s)}, avail {s['finite_avail']:.3f}, dRes vs ArbCal-Rank {dv['mean']:+.2f} [{dv['lo']:+.2f}, {dv['hi']:+.2f}]")
    (OUT / 'tab_scalar_comparison_rows.tex').write_text('\n'.join(aux) + '\n')
    for f in ('tab_surface_main_2018_2022.tex', 'tab_limits_main_t3_2018_2022.tex', 'tab_validation_2023_rows.tex', 'tab_gaussian_robustness_rows.tex', 'tab_scalar_comparison_rows.tex'):
        print(f'wrote results/{f}')
if __name__ == '__main__':
    main()
