from __future__ import annotations
import argparse
import importlib.util
import json
from pathlib import Path
import numpy as np
import lib_fullcal as fl
from arbcal.polyhedron import polyhedron_rows, FAMILIES

def _load_arb():
    spec = importlib.util.spec_from_file_location('arbm', Path(__file__).parent / 'lib_arb_margin.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--panel', required=True)
    ap.add_argument('--outdir', required=True)
    args = ap.parse_args()
    outdir = Path(args.outdir)
    arb = _load_arb()
    days, S, F, DISC, C = fl.load_panel(args.panel)
    manifest = fl.load_manifest()
    masks = fl.panel_masks(days, manifest)
    G, h, fam = polyhedron_rows()
    Gm, hm, famm, meta = arb.build_row_map()
    ok, checks = arb.verify_row_map(Gm, hm, famm, G, h, fam)
    assert ok, checks
    z = np.load(outdir / 'fullcal_arrays.npz', allow_pickle=True)
    ts = np.asarray(z['expa_rw_t'], int)

    def inf_thresholds(x):
        x = np.asarray(x, float).copy()
        x[~np.isfinite(x)] = np.inf
        return x
    rep = {'t': ts, 'dates': np.asarray(days)[ts], 'Shat': np.asarray(z['expa_rw_Shat'], float), 'proj_c': np.asarray(z['expa_rw_proj_c'], float), 'q_p': inf_thresholds(z['expa_rw_q_prj']), 'q_r': inf_thresholds(z['expa_rw_q_raw']), 'lam': np.asarray(z['expa_rw_lam'], float), 'wshape': np.asarray(z['expa_rw_wshape'], float), 'cov_raw': np.asarray(z['expa_rw_cov_raw'], float), 'cov_box': np.asarray(z['expa_rw_cov_box'], float), 'cov_prj': np.asarray(z['expa_rw_cov_prj'], float)}
    marg = arb.analytic_margins(rep, G, h)
    Mb, winb, fammax_b, winfam_b = arb.per_date_summary(marg['m_ball'], fam)
    Mx, winx, fammax_x, winfam_x = arb.per_date_summary(marg['m_box'], fam)
    out = {'metadata': {'units': 'normalized_bp', 'normalization': 'constraint_row_l1', 'definition': 'M_t = 1e4 * max_l sup_{c in C_t} [h_l - g_l.c]_+ / ||g_l||_1', 'row_map_verified': True, 'gap_aware_inputs': True}, 'periods': {}}
    for suffix, period in (('2018_2022', 'primary'), ('2023', 'y2023')):
        pm = masks[period][ts]
        n = int(pm.sum())
        blk = {'n_dates': n}
        for name, M, wf in (('raw_ball', Mb[pm], winfam_b[pm]), ('joint_box', Mx[pm], winfam_x[pm])):
            fin = M[np.isfinite(M)]
            p, lo, hi = arb.mbb_stat([M], lambda a_: arb.med(a_[0]))
            blk[name] = {'median': float(np.median(M)), 'median_ci95': [lo, hi], 'mean_finite': float(np.mean(fin)) if len(fin) else None, 'p90': float(np.percentile(M, 90)), 'max_finite': float(np.max(fin)) if len(fin) else None, 'n_inf_threshold': int(np.sum(~np.isfinite(M))), 'violator_date_rate': float(np.mean(M > 10000.0 * arb.TOL_CERT)), 'winning_family_frac': {f: float(np.mean(wf == f)) for f in FAMILIES}}
        blk['arbcal_set'] = {'median': 0.0, 'note': 'zero by construction (set subset of A)'}
        out['periods'][suffix] = blk
        cov = {'ball': float(np.mean(rep['cov_raw'][pm])), 'box': float(np.mean(rep['cov_box'][pm])), 'set': float(np.mean(rep['cov_prj'][pm]))}
        qr, qp = (rep['q_r'][pm], rep['q_p'][pm])
        mr = {'ball': float(np.mean(qr[np.isfinite(qr)])), 'set': float(np.mean(qp[np.isfinite(qp)]))}
        tab = '\n'.join(['% AUTO-GENERATED by scripts/run_arb.py -- candidate, NOT wired into main.tex.', '\\begin{tabular}{@{}lcccc@{}}', '\\toprule', 'method & joint coverage & dates admitting & mean radius & median worst admitted\\\\', ' & & violator & & margin (normalized bp)\\\\', '\\midrule', f"raw joint ball & ${cov['ball']:.3f}$ & $1.000$ & ${mr['ball']:.4f}$ & ${blk['raw_ball']['median']:.1f}$\\\\", f"joint box & ${cov['box']:.3f}$ & $1.000$ & --- & ${blk['joint_box']['median']:.1f}$\\\\", f"\\textbf{{ArbCal-Set}} & $\\mathbf{{{cov['set']:.3f}}}$ & $\\mathbf{{0.000}}$ & ${mr['set']:.4f}$ & $\\mathbf{{0}}$\\\\", '\\bottomrule', '\\end{tabular}', f"% n dates: {n}; box inf-threshold dates: {blk['joint_box']['n_inf_threshold']}"]) + '\n'
        (outdir / f'tab_arbitrage_candidate_{suffix}.tex').write_text(tab)
    (outdir / 'arb_margin_fullcal.json').write_text(json.dumps(out, indent=1, default=float))
    print(json.dumps({s: {k: v if not isinstance(v, dict) else {kk: v[kk] for kk in ('median', 'p90', 'violator_date_rate') if kk in v} for k, v in blk.items() if k != 'arbcal_set'} for s, blk in out['periods'].items()}, indent=1, default=str))
if __name__ == '__main__':
    main()
